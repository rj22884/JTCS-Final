def _f(
    key: str,
    label: str,
    *,
    section: str,
    field_type: str = "text",
    source: str = "customer",
    locked: bool = True,
    always_on: bool = False,
    always_required: bool = False,
    maxlength: int | None = None,
    options: list | None = None,
    features: list | None = None,
    hint: str = "",
    label_template: str = "",
    tier: str = "basic",
    db: str = "",
    visible_when: dict | None = None,
    visible_when_any: dict | None = None,
) -> dict[str, Any]:
    return {
        "key": key,
        "label": label,
        "section": section,
        "type": field_type,
        "source": source,
        "locked": locked,
        "always_on": always_on,
        "always_required": always_required,
        "maxlength": maxlength,
        "options": options or [],
        "features": features or [],
        "hint": hint,
        "label_template": label_template or label,
        "tier": tier,
        "db": db,
        "required": always_required,
        "visible_when": visible_when or {},
        "visible_when_any": visible_when_any or {},
    }


def _prop(
    key: str,
    label: str,
    *,
    field_type: str = "text",
    maxlength: int | None = None,
    options: list | None = None,
    features: list | None = None,
    hint: str = "",
    visible_when: dict | None = None,
    visible_when_any: dict | None = None,
) -> dict[str, Any]:
    return _f(
        key,
        label,
        section="property",
        field_type=field_type,
        source="property",
        locked=True,
        maxlength=maxlength,
        options=options,
        features=features,
        hint=hint,
        visible_when=visible_when if visible_when is not None else dict(WHEN_PROPERTY),
        visible_when_any=visible_when_any,
    )


